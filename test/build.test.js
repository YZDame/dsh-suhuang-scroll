import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

const clientUrl = new URL("../client.js", import.meta.url);
const packageUrl = new URL("../package.json", import.meta.url);

test("the committed bundle keeps the host loader contract", () => {
  const code = readFileSync(clientUrl, "utf8");
  assert.match(code, /Generated by scripts\/build-client\.mjs/);
  assert.match(code, /window\.__ModuleLoader__\.load\(\{/);
  assert.match(code, /id: "dsh-suhuang-scroll"/);
  assert.match(code, /factory: \(require\) => \{/);
  assert.match(code, /return Object\.defineProperty\(module\.exports, Symbol\.toStringTag/);
});

test("React and host primitives stay external", () => {
  const code = readFileSync(clientUrl, "utf8");
  assert.match(code, /require\("react"\)/);
  assert.match(code, /require\("@deepseek-ai\/dsh-client-ui-primitives"\)/);
  assert.doesNotMatch(code, /react-dom\.development/);
  assert.doesNotMatch(code, /__SECRET_INTERNALS/);
});

test("the package manifest ships the built client and declares the web platform", () => {
  const manifest = JSON.parse(readFileSync(packageUrl, "utf8"));
  assert.equal(manifest.exports["./client"], "./client.js");
  assert.ok(manifest.files.includes("client.js"));
  assert.equal(manifest.dsh.client.platform, "web");
  assert.equal(manifest.scripts.build, "node scripts/build-client.mjs");
  assert.equal(manifest.scripts["build:check"], "node scripts/build-client.mjs --check");
  assert.deepEqual(Object.keys(manifest.devDependencies).sort(), ["esbuild", "react", "react-dom"]);
});
