// Build the DSH client bundle.
//
// The host serves a prebuilt CJS bundle and never compiles plugin sources, so
// `client.js` is generated from `src/client/` and committed. Run `npm run build`
// after editing sources; `npm run build:check` fails when the committed bundle is
// stale (used by `pretest` and CI).
//
// The bundle is wrapped in the host's module-loader facade:
//   window.__ModuleLoader__.load({ id: "<npm package name>", factory: (require) => { ... } })
// Every host-baseline module stays external: bundling React or the primitives
// would create a second React instance and break hooks.

import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";

const PACKAGE_NAME = "dsh-suhuang-scroll";
const OUTPUT = "client.js";

// The shell's frozen PLATFORM_MODULES table. These specifiers resolve through the
// loader's `require`, so they must never be bundled.
const BASELINE_EXTERNAL = [
  "react",
  "react/jsx-runtime",
  "react-dom",
  "react-dom/client",
  "@deepseek-ai/cordis",
  "@deepseek-ai/dsh-client-store",
  "@deepseek-ai/dsh-client-ui-slots",
  "@deepseek-ai/dsh-client-ui-primitives",
  "@deepseek-ai/dsh-client-ui-dockkit",
];

function wrapBundle(code) {
  return `// Generated by scripts/build-client.mjs from src/client — do not edit by hand.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_NAME)},
  factory: (require) => {
"use strict";
const module = { exports: {} };
const exports = module.exports;
${code}
return Object.defineProperty(module.exports, Symbol.toStringTag, { value: "Module" });
  },
});
`;
}

const result = await build({
  entryPoints: ["src/client/index.jsx"],
  bundle: true,
  write: false,
  format: "cjs",
  platform: "browser",
  target: ["es2022"],
  jsx: "automatic",
  external: BASELINE_EXTERNAL,
  loader: { ".css": "text" },
  legalComments: "none",
  sourcemap: false,
  minify: false,
  define: { "process.env.NODE_ENV": '"production"' },
  logLevel: "silent",
});

const code = wrapBundle(result.outputFiles[0].text);
const check = process.argv.includes("--check");

if (check) {
  const committed = await readFile(OUTPUT, "utf8");
  if (committed !== code) {
    console.error(`${OUTPUT} is stale. Run \`npm run build\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date (${code.length} bytes).`);
} else {
  await writeFile(OUTPUT, code);
  console.log(`wrote ${OUTPUT} (${code.length} bytes)`);
}
